from __future__ import annotations

from typing import Any
from uuid import UUID

from opencode_web.opencode_client import OpenCodeClient


class RecordingOpenCodeClient(OpenCodeClient):
    def __init__(self) -> None:
        self.requests: list[tuple[str, str, dict[str, Any]]] = []

    async def _request(self, method: str, path: str, **kwargs: Any) -> Any:
        self.requests.append((method, path, kwargs))
        if method == "POST":
            return {"id": "session-1", "title": "New session - timestamp"}
        if path == "/session":
            return [{"id": "session-1", "title": "Generated by OpenCode"}]
        return {"id": "session-1", "title": "Generated by OpenCode"}


async def test_session_title_requests_are_owned_by_opencode() -> None:
    client = RecordingOpenCodeClient()

    created = await client.create_session()
    sessions = await client.sessions()
    session = await client.session("session-1")

    assert created["title"] == "New session - timestamp"
    assert sessions[0]["title"] == "Generated by OpenCode"
    assert session["title"] == "Generated by OpenCode"
    creation_key = client.requests[0][2]["json"]["metadata"]["shodanCreationKey"]
    assert UUID(creation_key).version == 4
    assert client.requests == [
        ("POST", "/session", {"json": {"metadata": {"shodanCreationKey": creation_key}}}),
        ("GET", "/session", {}),
        ("GET", "/session/session-1", {}),
    ]
