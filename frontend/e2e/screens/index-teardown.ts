import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { OUT_DIR, PROTO_DIR, RUNS_DIR } from './paths';
import { STATES, type ScreenState, type Theme } from './states';

const THEMES: Theme[] = ['light', 'dark'];

/** The prototype shot for a state × theme; light files may have no suffix. */
function protoSource(s: ScreenState, theme: Theme): string | null {
    const stem = s.proto ?? s.state;
    const base = stem ? `proto-${stem}` : 'proto';
    const names = theme === 'light' ? [`${base}-light.png`, ...(stem ? [`${base}.png`] : [])] : [`${base}-dark.png`];
    for (const n of names) {
        const p = join(PROTO_DIR, s.group, n);
        if (existsSync(p)) return p;
    }
    return null;
}

function readRun(s: ScreenState, theme: Theme): { captured: boolean; reason?: string } | null {
    const p = join(RUNS_DIR, `${s.group}__${s.state}__${theme}.json`);
    if (!existsSync(p)) return null;
    try {
        return JSON.parse(readFileSync(p, 'utf8'));
    } catch {
        return null;
    }
}

const cell = (v: string) => v.replace(/\|/g, '\\|').replace(/\n/g, ' ');

/** Copies the proto shots next to the live ones (`proto-<state>-<theme>.png`) and writes INDEX.md. */
export default async function indexTeardown(): Promise<void> {
    const rows: string[] = [];
    let captured = 0;
    let withProto = 0;
    for (const s of STATES) {
        mkdirSync(join(OUT_DIR, s.group), { recursive: true });
        for (const theme of THEMES) {
            const src = protoSource(s, theme);
            const protoRel = `${s.group}/proto-${s.state}-${theme}.png`;
            if (src) {
                copyFileSync(src, join(OUT_DIR, protoRel));
                withProto++;
            }
            const liveRel = `${s.group}/live-${s.state}-${theme}.png`;
            const run = readRun(s, theme);
            const ok = !!run?.captured && existsSync(join(OUT_DIR, liveRel));
            if (ok) captured++;
            const status = ok ? 'yes' : `no: ${run?.reason ?? 'not run yet'}`;
            rows.push(
                `| ${s.group} | ${s.state} | ${theme} | ${cell(s.how)} | ${src ? protoRel : `— (no proto; source ${relative(OUT_DIR, join(PROTO_DIR, s.group))})`} | ${ok ? liveRel : '—'} | ${cell(status)} |`,
            );
        }
    }
    const md = [
        '# Prototype vs live: screen index',
        '',
        'Generated by `bun run e2e:screens` (frontend/e2e/playwright.screens.config.ts, states in e2e/screens/states.ts).',
        'Live shots: mock server with `--fixed-now` (prototype now 2026-10-24 14:30 MSK), browser clock at the same',
        'moment, viewport 1440×790 CSS px, DPR 2, Europe/Moscow, ru-RU. Theme set through `localStorage["valeria.theme"]`',
        '(the app\'s own ui-state key) plus the matching `prefers-color-scheme`. Paths are relative to this file.',
        '',
        `Captured: ${captured} of ${STATES.length * 2} (state × theme); prototype shots found: ${withProto}.`,
        '',
        '| group | state | theme | how reached (URL + steps) | proto | live | captured? |',
        '|---|---|---|---|---|---|---|',
        ...rows,
        '',
    ].join('\n');
    writeFileSync(join(OUT_DIR, 'INDEX.md'), md);
}
